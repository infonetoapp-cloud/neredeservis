function normalizeSearchText(value) {
  return (value ?? "")
    .toString()
    .trim()
    .toLocaleLowerCase("tr")
    .replaceAll("ç", "c")
    .replaceAll("ğ", "g")
    .replaceAll("ı", "i")
    .replaceAll("ö", "o")
    .replaceAll("ş", "s")
    .replaceAll("ü", "u")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function tokenize(value) {
  return normalizeSearchText(value)
    .split(" ")
    .map((item) => item.trim())
    .filter(Boolean);
}

function toRadians(value) {
  return (value * Math.PI) / 180;
}

function haversineMeters(left, right) {
  const earthRadius = 6371000;
  const dLat = toRadians(right.lat - left.lat);
  const dLng = toRadians(right.lng - left.lng);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRadians(left.lat)) *
      Math.cos(toRadians(right.lat)) *
      Math.sin(dLng / 2) *
      Math.sin(dLng / 2);
  return 2 * earthRadius * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

function buildSearchField(place) {
  return normalizeSearchText([place.name, place.shortName, place.label, ...(place.aliases ?? [])].join(" "));
}

function scorePlace(place, normalizedQuery, tokens, proximity) {
  if (!normalizedQuery) {
    return place.importance * 100;
  }

  const searchField = buildSearchField(place);
  let score = place.importance * 100;

  if (searchField === normalizedQuery) {
    score += 1000;
  }
  if (searchField.startsWith(normalizedQuery)) {
    score += 420;
  }
  if (searchField.includes(normalizedQuery)) {
    score += 180;
  }

  for (const alias of place.aliases ?? []) {
    const normalizedAlias = normalizeSearchText(alias);
    if (normalizedAlias === normalizedQuery) {
      score += 720;
    } else if (normalizedAlias.startsWith(normalizedQuery)) {
      score += 260;
    } else if (normalizedAlias.includes(normalizedQuery)) {
      score += 110;
    }
  }

  for (const token of tokens) {
    if (searchField.includes(token)) {
      score += 55;
    }
  }

  if (proximity) {
    const distanceMeters = haversineMeters(proximity, place);
    if (distanceMeters < 1500) {
      score += 120;
    } else if (distanceMeters < 5000) {
      score += 75;
    } else if (distanceMeters < 15000) {
      score += 35;
    }
  }

  return score;
}

function toSuggestion(place, source = "bootstrap") {
  return {
    id: place.id,
    label: place.label,
    displayName: place.label,
    shortName: place.shortName || place.name,
    lat: place.lat,
    lng: place.lng,
    source,
  };
}

export function searchBootstrapPlaces({ query, limit = 6, proximity = null }) {
  const normalizedQuery = normalizeSearchText(query);
  const tokens = tokenize(query);

  return BOOTSTRAP_PLACES.map((place) => ({
    place,
    score: scorePlace(place, normalizedQuery, tokens, proximity),
  }))
    .filter((entry) => entry.score > 0)
    .sort((left, right) => right.score - left.score)
    .slice(0, limit)
    .map((entry) => toSuggestion(entry.place));
}

export function resolveBootstrapReverse({ lat, lng, maxDistanceMeters = 650 }) {
  const proximity = { lat, lng };
  let winner = null;

  for (const place of BOOTSTRAP_PLACES) {
    const distanceMeters = haversineMeters(proximity, place);
    if (!winner || distanceMeters < winner.distanceMeters) {
      winner = { place, distanceMeters };
    }
  }

  if (!winner || winner.distanceMeters > maxDistanceMeters) {
    return null;
  }

  return toSuggestion(winner.place);
}
